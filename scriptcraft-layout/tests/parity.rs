fn mix(mut h: u64, v: u64) -> u64 {
    for b in v.to_le_bytes() {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    h
}

const SEED: u64 = 0xcbf2_9ce4_8422_2325;

fn hash_pages(pages: &[paginate::Page]) -> u64 {
    let mut h = SEED;
    for (pi, page) in pages.iter().enumerate() {
        h = mix(h, pi as u64);
        for c in &page.chunks {
            h = mix(h, c.bi as u64);
            h = mix(h, c.start as u64);
            h = mix(h, c.end as u64);
            h = mix(h, c.more as u64);
            h = mix(h, c.contd as u64);
            h = mix(h, c.top as u64);
        }
    }
    h
}

const WRAP_WIDTHS: [usize; 10] = [18, 26, 28, 31, 35, 38, 43, 50, 58, 61];

fn hash_wrap(blocks: &[ScriptBlock]) -> u64 {
    let mut h = SEED;
    for (bi, b) in blocks.iter().enumerate() {
        h = mix(h, bi as u64);
        for (pi, para) in b.text.split('\n').enumerate() {
            h = mix(h, pi as u64);
            for cpl in WRAP_WIDTHS {
                h = mix(h, cpl as u64);
                for line in wrap::wrap_paragraph(para, cpl) {
                    h = mix(h, line.text.len() as u64);
                    for byte in line.text.bytes() {
                        h = mix(h, byte as u64);
                    }
                    h = mix(h, line.start as u64);
                    h = mix(h, line.end as u64);
                }
                h = mix(h, u64::MAX);
            }
        }
    }
    h
}

